#!/usr/bin/env python3
"""Writes tests/bank_fixture.h: a small .zip built from SYNTHETIC patches (written for this test, not taken from any bank),
so the zip / inflate / h2p / syx code can be tested without third-party data. Run: python tools/make_bank_fixture.py"""
import io
import os
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))

def h2p(name, am="Repro-5", **v):
    d = dict(FEnvAtk=0, FEnvDec=50, FEnvSus=30, FEnvRel=20, AEnvAtk=10, AEnvDec=60, AEnvSus=80, AEnvRel=25,
             OscAOct=1, OscAFreq=0, OscAFine=0, OscASaw=1, OscARect=0, OscAPW=50, OscASync=0, OscAVFM=0, OscAVPWM=0,
             OscBOct=2, OscBFreq=0, OscBFine=0, OscBSaw=0, OscBTri=1, OscBRect=0, OscBPW=50, OscBLow=0, OscBK=1,
             VModB=0, VModEnv=0, MixA=100, MixB=0, MixN=0, Cut=50, Res=25, Key=100, FEnv=40, FVMod=0, Pol=0, Glide=0)
    d.update(v)
    t = "/*@Meta\n\nBank:\n'Synthetic Test Bank'\n\nAuthor:\n'nobody'\n\n*/\n\n#AM=%s\n#Vers=301\n#Endian=little\n#nm=16\n#ms=none\n" % am
    t += "#cm=main\nCcOp=100.00\n#cm=MM1\nSource=1\nDest1=Filter:Cutoff\nDepth1=48.00\n"
    t += "#cm=FEnv\nAtk=%.2f\nDec=%.2f\nSus=%.2f\nRel=%.2f\nVelDep=59.00\n" % (d["FEnvAtk"], d["FEnvDec"], d["FEnvSus"], d["FEnvRel"])
    t += "#cm=AEnv\nAtk=%.2f\nDec=%.2f\nSus=%.2f\nRel=%.2f\nVelDep=56.50\n" % (d["AEnvAtk"], d["AEnvDec"], d["AEnvSus"], d["AEnvRel"])
    t += "#cm=OscA\nOct=%d\nFreq=%.2f\nFine=%.2f\nSawOn=%d\nRectOn=%d\nPWidth=%.2f\nSync=%d\nVModFM=%d\nVModPWM=%d\n" % (
        d["OscAOct"], d["OscAFreq"], d["OscAFine"], d["OscASaw"], d["OscARect"], d["OscAPW"], d["OscASync"], d["OscAVFM"], d["OscAVPWM"])
    t += "#cm=OscB\nOct=%d\nFreq=%.2f\nFine=%.2f\nSawOn=%d\nTriOn=%d\nRectOn=%d\nPWidth=%.2f\nLowFrq=%d\nKPitch=%d\n" % (
        d["OscBOct"], d["OscBFreq"], d["OscBFine"], d["OscBSaw"], d["OscBTri"], d["OscBRect"], d["OscBPW"], d["OscBLow"], d["OscBK"])
    t += "#cm=VMod\nOscBAmt=%.2f\nEnvAmt=%.2f\n#cm=MIX\nOscA=%.2f\nOscB=%.2f\nNoise=%.2f\n" % (d["VModB"], d["VModEnv"], d["MixA"], d["MixB"], d["MixN"])
    t += "#cm=Filter\nKTSrc=1\nCutoff=%.2f\nReso=%.2f\nKeyAmt=%.2f\nEnvAmt=%.2f\nVMod=%d\nGMod=1\nEnvPol=%d\n" % (d["Cut"], d["Res"], d["Key"], d["FEnv"], d["FVMod"], d["Pol"])
    t += "#cm=Glide\nAmt=%.2f\n" % d["Glide"]
    t += "\n\n\n// Section for ugly compressed binary Data\n// DON'T TOUCH THIS\n\n$$$$12\n?aamnmnmn\n#cm=OscA\nOct=3\n"   # keys after the tail must be ignored
    return t.encode()

files = {
    "Synthetic/01 Leads/Zed Lead.h2p": h2p("zed", Cut=70, Res=60, MixA=40, MixB=100, OscBSaw=1, OscBTri=0, OscASync=1),
    "Synthetic/01 Leads/alpha Pad.h2p": h2p("alpha", Cut=30, FVMod=1, VModEnv=10, OscAVFM=1, OscARect=1, OscASaw=0, Pol=1),
    "Synthetic/02 Bass/Mid Bass.h2p": h2p("mid", OscAOct=0, OscAFreq=6, Cut=20, Key=0, Glide=40, OscBK=0),
    "Synthetic/Other Synth.h2p": h2p("other", am="Zebra2"),
    "Synthetic/readme.txt": b"not a patch\n",
    "Synthetic/Pad (empty).h2p": b"#AM=Repro-5\n#cm=main\nCcOp=1\n",       # a Repro-5 file with no recognised keys
}
buf = io.BytesIO()
with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
    for k, v in files.items():
        z.writestr(k, v)
    z.writestr("Synthetic/Stored.h2p", h2p("stored", Cut=90))
    z.filelist[-1].compress_type = zipfile.ZIP_STORED
data = buf.getvalue()
# a stored entry needs its compress type set before writing, so rewrite properly
buf = io.BytesIO()
with zipfile.ZipFile(buf, "w") as z:
    for k, v in files.items():
        z.writestr(zipfile.ZipInfo(k), v, compress_type=zipfile.ZIP_DEFLATED)
    z.writestr(zipfile.ZipInfo("Synthetic/Stored.h2p"), h2p("stored", Cut=90), compress_type=zipfile.ZIP_STORED)
    z.writestr(zipfile.ZipInfo("Synthetic/"), b"")
data = buf.getvalue()
with open(os.path.join(HERE, "..", "tests", "bank_fixture.h"), "w", newline="\n") as f:
    f.write("/* Generated by tools/make_bank_fixture.py from SYNTHETIC patches - no third-party data. */\n")
    f.write("static const unsigned char k_fixture_zip[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
print("wrote tests/bank_fixture.h (%d bytes of zip)" % len(data))
